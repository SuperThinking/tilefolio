"""Tiny SQLite layer (stdlib only). One short-lived connection per unit of work."""
from __future__ import annotations

import sqlite3
from contextlib import contextmanager
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Iterator, Optional

from .config import settings

SCHEMA = """
CREATE TABLE IF NOT EXISTS users (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    google_sub  TEXT UNIQUE NOT NULL,
    email       TEXT,
    name        TEXT,
    created_at  TEXT DEFAULT (datetime('now'))
);

-- Local-first sync: the browser is the source of truth; this is the signed-in backup.
CREATE TABLE IF NOT EXISTS user_state (
    user_id     INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    state_json  TEXT NOT NULL,
    updated_at  INTEGER NOT NULL           -- client-supplied epoch ms (last-write-wins)
);

-- Daily AMFI NAV snapshots so we can compute MF day change (NAVAll.txt has no prev NAV).
CREATE TABLE IF NOT EXISTS nav_history (
    code      TEXT NOT NULL,
    nav_date  TEXT NOT NULL,               -- ISO yyyy-mm-dd
    nav       REAL NOT NULL,
    PRIMARY KEY (code, nav_date)
);

CREATE TABLE IF NOT EXISTS mf_schemes (
    code        TEXT PRIMARY KEY,          -- AMFI scheme code (same as mfapi.in)
    name        TEXT NOT NULL,
    isin_growth TEXT,
    isin_reinv  TEXT
);
CREATE INDEX IF NOT EXISTS ix_mf_isin_g ON mf_schemes(isin_growth);
CREATE INDEX IF NOT EXISTS ix_mf_isin_r ON mf_schemes(isin_reinv);

CREATE TABLE IF NOT EXISTS equities (
    symbol    TEXT NOT NULL,
    exchange  TEXT NOT NULL,               -- NSE (BSE later)
    name      TEXT NOT NULL,
    isin      TEXT,
    industry  TEXT,
    PRIMARY KEY (exchange, symbol)
);
CREATE INDEX IF NOT EXISTS ix_eq_isin ON equities(isin);

CREATE TABLE IF NOT EXISTS broker_requests (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    broker      TEXT NOT NULL,
    note        TEXT,
    user_id     INTEGER,
    created_at  TEXT DEFAULT (datetime('now'))
);

CREATE TABLE IF NOT EXISTS meta (
    key    TEXT PRIMARY KEY,
    value  TEXT
);

-- Anonymous API analytics. The UUID is generated by the browser and is not
-- joined to users/google accounts. Requests are aggregated by hour so this
-- stays small enough for the single-server deployment.
CREATE TABLE IF NOT EXISTS api_clients (
    client_uuid   TEXT PRIMARY KEY,
    first_seen_at TEXT NOT NULL,
    last_seen_at  TEXT NOT NULL,
    total_requests INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS api_client_buckets (
    bucket_start  TEXT NOT NULL,
    client_uuid   TEXT NOT NULL,
    request_count INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (bucket_start, client_uuid)
);

CREATE TABLE IF NOT EXISTS api_request_metrics (
    bucket_start       TEXT NOT NULL,
    method             TEXT NOT NULL,
    path               TEXT NOT NULL,
    status_code        INTEGER NOT NULL,
    request_count      INTEGER NOT NULL DEFAULT 0,
    duration_ms_sum    REAL NOT NULL DEFAULT 0,
    duration_ms_max    REAL NOT NULL DEFAULT 0,
    PRIMARY KEY (bucket_start, method, path, status_code)
);

CREATE INDEX IF NOT EXISTS ix_api_client_buckets_start ON api_client_buckets(bucket_start);
CREATE INDEX IF NOT EXISTS ix_api_request_metrics_start ON api_request_metrics(bucket_start);
"""

_db_path: Path = settings.db_path


def set_db_path(path: Path) -> None:
    """Used by tests to point at a temp database."""
    global _db_path
    _db_path = path
    init_db()


@contextmanager
def connect() -> Iterator[sqlite3.Connection]:
    conn = sqlite3.connect(str(_db_path), timeout=10)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    try:
        yield conn
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def init_db() -> None:
    with connect() as c:
        c.execute("PRAGMA journal_mode = WAL")
        c.executescript(SCHEMA)


def get_meta(key: str) -> Optional[str]:
    with connect() as c:
        row = c.execute("SELECT value FROM meta WHERE key = ?", (key,)).fetchone()
        return row["value"] if row else None


def set_meta(key: str, value: str) -> None:
    with connect() as c:
        c.execute(
            "INSERT INTO meta(key, value) VALUES(?, ?) ON CONFLICT(key) DO UPDATE SET value = excluded.value",
            (key, value),
        )


def _utc_now() -> datetime:
    return datetime.now(timezone.utc)


def _utc_text(value: datetime) -> str:
    return value.isoformat(timespec="seconds").replace("+00:00", "Z")


def record_api_request(client_uuid: Optional[str], method: str, path: str,
                       status_code: int, duration_ms: float) -> None:
    """Record one anonymous request without storing request bodies or query strings."""
    if not client_uuid:
        return
    now = _utc_now()
    timestamp = _utc_text(now)
    bucket = _utc_text(now.replace(minute=0, second=0, microsecond=0))
    method = method.upper()[:12]
    path = path[:200]
    status_code = int(status_code)
    duration_ms = max(0.0, float(duration_ms))
    with connect() as c:
        c.execute(
            "INSERT INTO api_clients(client_uuid, first_seen_at, last_seen_at, total_requests) "
            "VALUES(?,?,?,?) ON CONFLICT(client_uuid) DO UPDATE SET "
            "last_seen_at=excluded.last_seen_at, total_requests=api_clients.total_requests + 1",
            (client_uuid, timestamp, timestamp, 1),
        )
        c.execute(
            "INSERT INTO api_client_buckets(bucket_start, client_uuid, request_count) VALUES(?,?,1) "
            "ON CONFLICT(bucket_start, client_uuid) DO UPDATE SET "
            "request_count=api_client_buckets.request_count + 1",
            (bucket, client_uuid),
        )
        c.execute(
            "INSERT INTO api_request_metrics(bucket_start, method, path, status_code, request_count, "
            "duration_ms_sum, duration_ms_max) VALUES(?,?,?,?,1,?,?) "
            "ON CONFLICT(bucket_start, method, path, status_code) DO UPDATE SET "
            "request_count=api_request_metrics.request_count + 1, "
            "duration_ms_sum=api_request_metrics.duration_ms_sum + excluded.duration_ms_sum, "
            "duration_ms_max=MAX(api_request_metrics.duration_ms_max, excluded.duration_ms_max)",
            (bucket, method, path, status_code, duration_ms, duration_ms),
        )


def metrics_snapshot(hours: int = 24) -> dict:
    """Return a dashboard-friendly aggregate for the requested UTC time window."""
    hours = max(1, min(int(hours), 24 * 365))
    since = _utc_text((_utc_now() - timedelta(hours=hours)).replace(minute=0, second=0, microsecond=0))
    with connect() as c:
        totals = c.execute(
            "SELECT COALESCE(SUM(request_count), 0) AS requests, "
            "COALESCE(SUM(duration_ms_sum), 0) AS duration_ms, "
            "COALESCE(SUM(CASE WHEN status_code >= 400 THEN request_count ELSE 0 END), 0) AS errors "
            "FROM api_request_metrics WHERE bucket_start >= ?",
            (since,),
        ).fetchone()
        unique = c.execute(
            "SELECT COUNT(DISTINCT client_uuid) AS clients FROM api_client_buckets WHERE bucket_start >= ?",
            (since,),
        ).fetchone()["clients"]
        all_time = c.execute("SELECT COUNT(*) AS clients FROM api_clients").fetchone()["clients"]
        endpoints = c.execute(
            "SELECT method, path, SUM(request_count) AS requests, "
            "SUM(duration_ms_sum) AS duration_ms, "
            "SUM(CASE WHEN status_code >= 400 THEN request_count ELSE 0 END) AS errors "
            "FROM api_request_metrics WHERE bucket_start >= ? GROUP BY method, path "
            "ORDER BY requests DESC",
            (since,),
        ).fetchall()
        statuses = c.execute(
            "SELECT status_code, SUM(request_count) AS requests FROM api_request_metrics "
            "WHERE bucket_start >= ? GROUP BY status_code ORDER BY status_code",
            (since,),
        ).fetchall()
        hourly = c.execute(
            "SELECT bucket_start, SUM(request_count) AS requests, "
            "SUM(CASE WHEN status_code >= 400 THEN request_count ELSE 0 END) AS errors "
            "FROM api_request_metrics WHERE bucket_start >= ? GROUP BY bucket_start ORDER BY bucket_start",
            (since,),
        ).fetchall()

    total_requests = int(totals["requests"])
    duration_ms = float(totals["duration_ms"])
    return {
        "windowHours": hours,
        "requests": total_requests,
        "errors": int(totals["errors"]),
        "uniqueClients": int(unique),
        "allTimeUniqueClients": int(all_time),
        "avgLatencyMs": round(duration_ms / total_requests, 2) if total_requests else 0,
        "byEndpoint": [
            {
                "method": r["method"], "path": r["path"], "requests": int(r["requests"]),
                "errors": int(r["errors"]),
                "durationMs": round(float(r["duration_ms"]), 2),
                "avgLatencyMs": round(float(r["duration_ms"]) / int(r["requests"]), 2),
            }
            for r in endpoints
        ],
        "byStatus": [{"status": int(r["status_code"]), "requests": int(r["requests"])} for r in statuses],
        "hourly": [{"bucket": r["bucket_start"], "requests": int(r["requests"]), "errors": int(r["errors"])}
                   for r in hourly],
    }


def _prom_label(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def prometheus_metrics() -> str:
    """Return low-cardinality Prometheus text for an internal, token-protected endpoint."""
    now = _utc_now()
    since = _utc_text((now - timedelta(hours=24)).replace(minute=0, second=0, microsecond=0))
    with connect() as c:
        rows = c.execute(
            "SELECT method, path, status_code, SUM(request_count) AS requests, "
            "SUM(duration_ms_sum) AS duration_ms FROM api_request_metrics GROUP BY method, path, status_code"
        ).fetchall()
        clients = c.execute("SELECT COUNT(*) AS clients FROM api_clients").fetchone()["clients"]
        recent_clients = c.execute(
            "SELECT COUNT(DISTINCT client_uuid) AS clients FROM api_client_buckets WHERE bucket_start >= ?",
            (since,),
        ).fetchone()["clients"]

    lines = [
        "# HELP tilefolio_api_requests_total API requests recorded by method, path and status.",
        "# TYPE tilefolio_api_requests_total counter",
    ]
    for row in rows:
        labels = (f'method="{_prom_label(row["method"])}",path="{_prom_label(row["path"])}",'
                  f'status="{row["status_code"]}"')
        lines.append(f"tilefolio_api_requests_total{{{labels}}} {int(row['requests'])}")
    lines.extend([
        "# HELP tilefolio_api_request_duration_ms_sum Total request duration in milliseconds.",
        "# TYPE tilefolio_api_request_duration_ms_sum counter",
    ])
    for row in rows:
        labels = (f'method="{_prom_label(row["method"])}",path="{_prom_label(row["path"])}",'
                  f'status="{row["status_code"]}"')
        lines.append(f"tilefolio_api_request_duration_ms_sum{{{labels}}} {float(row['duration_ms']):.3f}")
    lines.extend([
        "# HELP tilefolio_unique_clients_total All anonymous client UUIDs seen by the API.",
        "# TYPE tilefolio_unique_clients_total gauge",
        f"tilefolio_unique_clients_total {int(clients)}",
        "# HELP tilefolio_unique_clients_24h Anonymous client UUIDs seen in the last 24 hours.",
        "# TYPE tilefolio_unique_clients_24h gauge",
        f"tilefolio_unique_clients_24h {int(recent_clients)}",
    ])
    return "\n".join(lines) + "\n"
